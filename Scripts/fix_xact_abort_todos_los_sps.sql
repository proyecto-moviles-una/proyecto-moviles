        UPDATE dbo.TB_USUARIO SET NUMERO_VERIFICACION = @NUEVO_CODIGO, FECHA_CODIGO_VERIFICACION = GETUTCDATE()
        WHERE CORREO_ELECTRONICO = @CORREO_ELECTRONICO AND ESTADO = 0;
        SET @IDRETURN = @@ROWCOUNT; SET @ERRORID = 0; SET @ERRORDESCRIPCION = N'';
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK;
        SET @IDRETURN = -1; SET @ERRORID = ERROR_NUMBER(); SET @ERRORDESCRIPCION = ERROR_MESSAGE();
    END CATCH
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_SOLICITAR_CAMBIO_CORREO
(
    @GUID_USUARIO     UNIQUEIDENTIFIER,
    @CORREO_NUEVO     NVARCHAR(150),
    @CODIGO           NVARCHAR(100),
    @IDRETURN         INT OUTPUT,
    @ERRORID          INT OUTPUT,
    @ERRORDESCRIPCION NVARCHAR(MAX) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT OFF;
    BEGIN TRY
        IF EXISTS (SELECT 1 FROM dbo.TB_USUARIO WHERE CORREO_ELECTRONICO = @CORREO_NUEVO AND GUID_USUARIO <> @GUID_USUARIO)
            BEGIN SET @IDRETURN=-1; SET @ERRORID=1; SET @ERRORDESCRIPCION=N'EL CORREO NUEVO YA ESTÁ EN USO'; RETURN; END
        IF NOT EXISTS (SELECT 1 FROM dbo.TB_USUARIO WHERE GUID_USUARIO = @GUID_USUARIO AND ESTADO = 1)
            BEGIN SET @IDRETURN=-1; SET @ERRORID=6; SET @ERRORDESCRIPCION=N'USUARIO NO ENCONTRADO O INACTIVO'; RETURN; END
        UPDATE dbo.TB_USUARIO
        SET CORREO_PENDIENTE = @CORREO_NUEVO, CODIGO_CAMBIO_CORREO = @CODIGO, FECHA_CODIGO_CORREO = GETDATE()
        WHERE GUID_USUARIO = @GUID_USUARIO;
        SET @IDRETURN = @@ROWCOUNT; SET @ERRORID = 0; SET @ERRORDESCRIPCION = N'';
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK;
        SET @IDRETURN = -1; SET @ERRORID = ERROR_NUMBER(); SET @ERRORDESCRIPCION = ERROR_MESSAGE();
    END CATCH
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_CONFIRMAR_CAMBIO_CORREO
(
    @GUID_USUARIO     UNIQUEIDENTIFIER,
    @CODIGO           NVARCHAR(100),
    @IDRETURN         INT OUTPUT,
    @ERRORID          INT OUTPUT,
    @ERRORDESCRIPCION NVARCHAR(MAX) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT OFF;
    BEGIN TRY
        DECLARE @CORREO_PENDIENTE NVARCHAR(150), @CODIGO_GUARDADO NVARCHAR(100), @FECHA_CODIGO DATETIME;
        SELECT @CORREO_PENDIENTE = CORREO_PENDIENTE, @CODIGO_GUARDADO = CODIGO_CAMBIO_CORREO, @FECHA_CODIGO = FECHA_CODIGO_CORREO
        FROM dbo.TB_USUARIO WHERE GUID_USUARIO = @GUID_USUARIO AND ESTADO = 1;
        IF @CORREO_PENDIENTE IS NULL OR @CODIGO_GUARDADO IS NULL
            BEGIN SET @IDRETURN=-1; SET @ERRORID=12; SET @ERRORDESCRIPCION=N'NO HAY SOLICITUD PENDIENTE'; RETURN; END
        IF DATEDIFF(MINUTE, @FECHA_CODIGO, GETDATE()) > 30
        BEGIN
            UPDATE dbo.TB_USUARIO SET CORREO_PENDIENTE=NULL, CODIGO_CAMBIO_CORREO=NULL, FECHA_CODIGO_CORREO=NULL WHERE GUID_USUARIO=@GUID_USUARIO;
            SET @IDRETURN=-1; SET @ERRORID=12; SET @ERRORDESCRIPCION=N'EL CÓDIGO HA EXPIRADO'; RETURN;
        END
        IF @CODIGO_GUARDADO <> @CODIGO
            BEGIN SET @IDRETURN=-1; SET @ERRORID=43; SET @ERRORDESCRIPCION=N'CÓDIGO INCORRECTO'; RETURN; END
        UPDATE dbo.TB_USUARIO
        SET CORREO_ELECTRONICO=@CORREO_PENDIENTE, CORREO_PENDIENTE=NULL, CODIGO_CAMBIO_CORREO=NULL, FECHA_CODIGO_CORREO=NULL
        WHERE GUID_USUARIO=@GUID_USUARIO;
        SET @IDRETURN = @@ROWCOUNT; SET @ERRORID = 0; SET @ERRORDESCRIPCION = N'';
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK;
        SET @IDRETURN = -1; SET @ERRORID = ERROR_NUMBER(); SET @ERRORDESCRIPCION = ERROR_MESSAGE();
    END CATCH
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_REACTIVAR_USUARIO
(
    @CORREO_ELECTRONICO NVARCHAR(100),
    @CODIGO             NVARCHAR(100),
    @IDRETURN           INT OUTPUT,
    @ERRORID            INT OUTPUT,
    @ERRORDESCRIPCION   NVARCHAR(MAX) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT OFF;
    BEGIN TRY
        DECLARE @ESTADO INT, @CODIGO_GUARDADO NVARCHAR(100), @FECHA_CODIGO DATETIME;
        SELECT @ESTADO=ESTADO, @CODIGO_GUARDADO=NUMERO_VERIFICACION, @FECHA_CODIGO=FECHA_CODIGO_VERIFICACION
        FROM dbo.TB_USUARIO WHERE CORREO_ELECTRONICO=@CORREO_ELECTRONICO;
        IF @ESTADO IS NULL  BEGIN SET @IDRETURN=-1; SET @ERRORID=14; SET @ERRORDESCRIPCION=N'CORREO NO REGISTRADO';          RETURN; END
        IF @ESTADO <> 2     BEGIN SET @IDRETURN=-1; SET @ERRORID=47; SET @ERRORDESCRIPCION=N'LA CUENTA NO ESTÁ DESACTIVADA'; RETURN; END
        IF @CODIGO_GUARDADO IS NULL OR @FECHA_CODIGO IS NULL
                            BEGIN SET @IDRETURN=-1; SET @ERRORID=12; SET @ERRORDESCRIPCION=N'SIN SOLICITUD PENDIENTE';        RETURN; END
        IF DATEDIFF(MINUTE, @FECHA_CODIGO, GETDATE()) > 30
        BEGIN
            UPDATE dbo.TB_USUARIO SET NUMERO_VERIFICACION=NULL, FECHA_CODIGO_VERIFICACION=NULL WHERE CORREO_ELECTRONICO=@CORREO_ELECTRONICO;
            SET @IDRETURN=-1; SET @ERRORID=12; SET @ERRORDESCRIPCION=N'EL CÓDIGO HA EXPIRADO'; RETURN;
        END
        IF @CODIGO_GUARDADO <> @CODIGO BEGIN SET @IDRETURN=-1; SET @ERRORID=45; SET @ERRORDESCRIPCION=N'CÓDIGO INCORRECTO'; RETURN; END
        UPDATE dbo.TB_USUARIO SET ESTADO=1, NUMERO_VERIFICACION=NULL, FECHA_CODIGO_VERIFICACION=NULL
        WHERE CORREO_ELECTRONICO=@CORREO_ELECTRONICO AND ESTADO=2;
        SET @IDRETURN = @@ROWCOUNT; SET @ERRORID = 0; SET @ERRORDESCRIPCION = N'';
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK;
        SET @IDRETURN = -1; SET @ERRORID = ERROR_NUMBER(); SET @ERRORDESCRIPCION = ERROR_MESSAGE();
    END CATCH
END
GO

